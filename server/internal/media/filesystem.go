// Filesystem layout under the root (mode 0750 directories, 0640 files,
// owned by the process user):
//
//	objects/<prefix>/<xx>/<name>   stored objects (key "<prefix>/<name>")
//	uploads/<upload id>/<n>.<md5>  parts of unfinished uploads (the name
//	                               carries the etag, so completing never
//	                               re-reads the data to check it)
//	tmp/                           files being written (renamed when done)
//
// Keys are generated by the server (random or uuid names); a key that does
// not match keyPattern is refused, so no path ever comes from a user.
const (
	dirMode  = 0o750
	fileMode = 0o640
)

var (
	keyPattern      = regexp.MustCompile(`^[a-z]{1,16}/[A-Za-z0-9_-][A-Za-z0-9._-]{1,80}$`)
	uploadIDPattern = regexp.MustCompile(`^[a-f0-9]{32}$`)
)

// Filesystem implements Objects on a local directory. Every write goes to
// a temporary file that is synced and renamed into place, so a crash never
// leaves a partial object under its key.
type Filesystem struct {
	root string
}

// NewFilesystem prepares root (creating its directories) and checks it is
// writable.
func NewFilesystem(root string) (*Filesystem, error) {
	if !filepath.IsAbs(root) {
		return nil, fmt.Errorf("media: storage root %q must be absolute", root)
	}
	f := &Filesystem{root: filepath.Clean(root)}
	for _, d := range []string{"objects", "uploads", "tmp"} {
		if err := os.MkdirAll(filepath.Join(f.root, d), dirMode); err != nil {
			return nil, fmt.Errorf("media: storage root: %w", err)
		}
	}
	return f, f.Ping(context.Background())
}

func (f *Filesystem) path(key string) (string, error) {
	if !keyPattern.MatchString(key) || strings.Contains(key, "..") {
		return "", fmt.Errorf("media: invalid object key %q", key)
	}
	prefix, name, _ := strings.Cut(key, "/")
	shard := strings.ToLower(name[:2])
	return filepath.Join(f.root, "objects", prefix, shard, name), nil
}

func (f *Filesystem) uploadDir(uploadID string) (string, error) {
	if !uploadIDPattern.MatchString(uploadID) {
		return "", fmt.Errorf("media: %w: upload %q", ErrNotFound, uploadID)
	}
	return filepath.Join(f.root, "uploads", uploadID), nil
}

// writeAtomic streams r into a temporary file, syncs it and renames it to
// dst; it returns the byte count and MD5 of what was written.
func (f *Filesystem) writeAtomic(dst string, r io.Reader) (int64, string, error) {
	if err := os.MkdirAll(filepath.Dir(dst), dirMode); err != nil {
		return 0, "", fmt.Errorf("media: mkdir: %w", err)
	}
	tmp, err := os.CreateTemp(filepath.Join(f.root, "tmp"), "w-*")
	if err != nil {
		return 0, "", fmt.Errorf("media: temp file: %w", err)
	}
	ok := false
	defer func() {
		if !ok {
			_ = tmp.Close()
			_ = os.Remove(tmp.Name())
		}
	}()
	if err := tmp.Chmod(fileMode); err != nil {
		return 0, "", fmt.Errorf("media: chmod: %w", err)
	}
	sum := md5.New()
	w := bufio.NewWriterSize(io.MultiWriter(tmp, sum), 256<<10)
	n, err := io.Copy(w, r)
	if err == nil {
		err = w.Flush()
	}
	if err != nil {
		return 0, "", fmt.Errorf("media: write: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		return 0, "", fmt.Errorf("media: sync: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return 0, "", fmt.Errorf("media: close: %w", err)
	}
	if err := os.Rename(tmp.Name(), dst); err != nil {
		return 0, "", fmt.Errorf("media: rename: %w", err)
	}
	ok = true
	syncDir(filepath.Dir(dst))
	return n, `"` + hex.EncodeToString(sum.Sum(nil)) + `"`, nil
}

// syncDir makes a rename durable; failures only weaken crash safety.
func syncDir(dir string) {
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		_ = d.Close()
	}
}

func (f *Filesystem) CreateMultipart(_ context.Context, _ string) (string, error) {
	id := strings.ReplaceAll(newUUID(), "-", "")
	if err := os.MkdirAll(filepath.Join(f.root, "uploads", id), dirMode); err != nil {
		return "", fmt.Errorf("media: create upload: %w", err)
	}
	return id, nil
}

// PresignPart is not available: browsers upload parts through the media
// host (proxy mode).
func (f *Filesystem) PresignPart(context.Context, string, string, int, time.Duration) (string, error) {
	return "", errors.New("media: the filesystem storage takes parts through the media host only")
}

func (f *Filesystem) UploadPart(_ context.Context, _, uploadID string, part int, body io.Reader, size int64) (Part, error) {
	dir, err := f.uploadDir(uploadID)
	if err != nil {
		return Part{}, err
	}
	if _, err := os.Stat(dir); err != nil {
		return Part{}, fmt.Errorf("media: upload part: %w", ErrNotFound)
	}
	tmpName := filepath.Join(dir, strconv.Itoa(part)+".writing")
	n, etag, err := f.writeAtomic(tmpName, io.LimitReader(body, size))
	if err != nil {
		return Part{}, err
	}
	if n != size {
		_ = os.Remove(tmpName)
		return Part{}, fmt.Errorf("media: part %d has %d of %d bytes", part, n, size)
	}
	// A part uploaded again replaces the earlier copy.
	old, _ := filepath.Glob(filepath.Join(dir, strconv.Itoa(part)+".*"))
	for _, o := range old {
		if o != tmpName {
			_ = os.Remove(o)
		}
	}
	if err := os.Rename(tmpName, filepath.Join(dir, strconv.Itoa(part)+"."+strings.Trim(etag, `"`))); err != nil {
		return Part{}, fmt.Errorf("media: store part: %w", err)
	}
	return Part{Number: part, ETag: etag, Size: n}, nil
}

func (f *Filesystem) CopyPart(ctx context.Context, src, key, uploadID string, part int, offset, length int64) (Part, error) {
	r, err := f.Get(ctx, src, offset, length)
	if err != nil {
		return Part{}, err
	}
	defer func() { _ = r.Close() }()
	return f.UploadPart(ctx, key, uploadID, part, r, length)
}

func (f *Filesystem) ListParts(_ context.Context, _, uploadID string) ([]Part, error) {
	dir, err := f.uploadDir(uploadID)
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, fmt.Errorf("media: list parts: %w", ErrNotFound)
	}
	if err != nil {
		return nil, fmt.Errorf("media: list parts: %w", err)
	}
	var out []Part
	for _, e := range entries {
		num, sum, ok := strings.Cut(e.Name(), ".")
		n, err := strconv.Atoi(num)
		if !ok || err != nil || len(sum) != 32 {
			continue
		}
		info, err := e.Info()
		if err != nil {
			return nil, fmt.Errorf("media: list parts: %w", err)
		}
		out = append(out, Part{Number: n, ETag: `"` + sum + `"`, Size: info.Size()})
	}
	slices.SortFunc(out, func(a, b Part) int { return a.Number - b.Number })
	return out, nil
}

// CompleteMultipart joins the parts (whose etags must match) into the
// object and drops the upload.
func (f *Filesystem) CompleteMultipart(ctx context.Context, key, uploadID string, parts []Part) error {
	dir, err := f.uploadDir(uploadID)
	if err != nil {
		return err
	}
	stored, err := f.ListParts(ctx, key, uploadID)
	if err != nil {
		return err
	}
	byNumber := map[int]Part{}
	for _, p := range stored {
		byNumber[p.Number] = p
	}
	files := make([]io.Reader, 0, len(parts))
	var closers []io.Closer
	defer func() {
		for _, c := range closers {
			_ = c.Close()
		}
	}()
	for i, p := range parts {
		s, ok := byNumber[p.Number]
		if !ok || strings.Trim(s.ETag, `"`) != strings.Trim(p.ETag, `"`) || (i > 0 && p.Number <= parts[i-1].Number) {
			return fmt.Errorf("media: complete multipart: InvalidPart %d", p.Number)
		}
		file, err := os.Open(filepath.Join(dir, strconv.Itoa(p.Number)+"."+strings.Trim(s.ETag, `"`)))
		if err != nil {
			return fmt.Errorf("media: open part: %w", err)
		}
		closers = append(closers, file)
		files = append(files, file)
	}
	dst, err := f.path(key)
	if err != nil {
		return err
	}
	if _, _, err := f.writeAtomic(dst, io.MultiReader(files...)); err != nil {
		return err
	}
	return f.AbortMultipart(ctx, key, uploadID)
}

func (f *Filesystem) AbortMultipart(_ context.Context, _, uploadID string) error {
	dir, err := f.uploadDir(uploadID)
	if err != nil {
		return err
	}
	if _, err := os.Stat(dir); errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("media: abort: %w", ErrNotFound)
	}
	if err := os.RemoveAll(dir); err != nil {
		return fmt.Errorf("media: abort: %w", err)
	}
	return nil
}

// sectionReadCloser closes the file under a section reader.
type sectionReadCloser struct {
	io.Reader
	file *os.File
}

func (s sectionReadCloser) Close() error { return s.file.Close() }

func (f *Filesystem) Get(_ context.Context, key string, offset, length int64) (io.ReadCloser, error) {
	p, err := f.path(key)
	if err != nil {
		return nil, err
	}
	file, err := os.Open(p)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, fmt.Errorf("media: get: %w", ErrNotFound)
	}
	if err != nil {
		return nil, fmt.Errorf("media: get: %w", err)
	}
	info, err := file.Stat()
	if err != nil {
		_ = file.Close()
		return nil, fmt.Errorf("media: get: %w", err)
	}
	if length < 0 {
		length = info.Size() - offset
	}
	return sectionReadCloser{Reader: io.NewSectionReader(file, offset, length), file: file}, nil
}

// PresignGet returns a file: URL for ffmpeg, which reads it locally.
func (f *Filesystem) PresignGet(_ context.Context, key string, _ time.Duration) (string, error) {
	p, err := f.path(key)
	if err != nil {
		return "", err
	}
	return "file:" + p, nil
}

func (f *Filesystem) Size(_ context.Context, key string) (int64, error) {
	p, err := f.path(key)
	if err != nil {
		return 0, err
	}
	info, err := os.Stat(p)
	if errors.Is(err, fs.ErrNotExist) {
		return 0, fmt.Errorf("media: stat: %w", ErrNotFound)
	}
	if err != nil {
		return 0, fmt.Errorf("media: stat: %w", err)
	}
	return info.Size(), nil
}

func (f *Filesystem) Put(_ context.Context, key string, data []byte, _ string) error {
	p, err := f.path(key)
	if err != nil {
		return err
	}
	_, _, err = f.writeAtomic(p, bytes.NewReader(data))
	return err
}

// Copy hard-links dst to src (same file system; objects are never changed
// in place), or copies when linking is not possible.
func (f *Filesystem) Copy(_ context.Context, src, dst string) error {
	sp, err := f.path(src)
	if err != nil {
		return err
	}
	dp, err := f.path(dst)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dp), dirMode); err != nil {
		return fmt.Errorf("media: mkdir: %w", err)
	}
	if err := os.Link(sp, dp); err == nil {
		syncDir(filepath.Dir(dp))
		return nil
	}
	in, err := os.Open(sp)
	if errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("media: copy: %w", ErrNotFound)
	}
	if err != nil {
		return fmt.Errorf("media: copy: %w", err)
	}
	defer func() { _ = in.Close() }()
	_, _, err = f.writeAtomic(dp, in)
	return err
}

func (f *Filesystem) Delete(_ context.Context, key string) error {
	p, err := f.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("media: delete: %w", err)
	}
	return nil
}

// Ping checks the root is a writable directory.
func (f *Filesystem) Ping(context.Context) error {
	tmp, err := os.CreateTemp(filepath.Join(f.root, "tmp"), "ping-*")
	if err != nil {
		return fmt.Errorf("media: storage root not writable: %w", err)
	}
	_ = tmp.Close()
	return os.Remove(tmp.Name())
}

// FreeBytes reports the space left for an unprivileged writer on the
// root's file system.
func (f *Filesystem) FreeBytes() (int64, error) {
	var st syscall.Statfs_t
	if err := syscall.Statfs(f.root, &st); err != nil {
		return 0, fmt.Errorf("media: statfs: %w", err)
	}
	return int64(uint64(st.Bavail) * uint64(st.Bsize)), nil //nolint:gosec // block counts of a real file system fit
}

// CleanTemp removes temporary files older than age (left by a crash).
func (f *Filesystem) CleanTemp(age time.Duration) {
	entries, err := os.ReadDir(filepath.Join(f.root, "tmp"))
	if err != nil {
		return
	}
	for _, e := range entries {
		if info, err := e.Info(); err == nil && time.Since(info.ModTime()) > age {
			_ = os.Remove(filepath.Join(f.root, "tmp", e.Name()))
		}
	}
}
