// Builds the local portal of `tunelo http` into dist/portal, then writes
// dist/release-entry.ts: the entry `bun build --compile` takes for a
// release. It imports every portal file with `{ type: "file" }`, so Bun
// embeds them in the binary, hands their paths to the CLI and starts it.
//
//   pnpm --filter @achoo254/tunelo-agent build:portal
//   bun build --compile apps/agent/dist/release-entry.ts --outfile tunelo
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const agentDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const distDir = join(agentDir, "dist");
const portalDir = join(distDir, "portal");

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? listFiles(full) : [full];
  });
}

await build({ configFile: join(agentDir, "vite.config.portal.ts"), logLevel: "warn" });

const files = listFiles(portalDir).map((file) => relative(portalDir, file).split(sep).join("/")).sort();
if (!files.includes("index.html")) throw new Error("the portal build has no index.html");

const lines = [
  "// Generated by scripts/build-portal.ts; not committed. The release entry: the CLI with the portal embedded.",
  'import { setPortalAssets } from "../src/tunnels/portal-assets.ts";',
  ...files.map((file, i) => `import f${i} from ${JSON.stringify(`./portal/${file}`)} with { type: "file" };`),
  "",
  "setPortalAssets({",
  ...files.map((file, i) => `  ${JSON.stringify(`/${file}`)}: f${i},`),
  "});",
  'await import("../src/cli.ts");',
  "",
];
writeFileSync(join(distDir, "release-entry.ts"), lines.join("\n"));
console.log(`portal: ${files.length} files in ${relative(process.cwd(), portalDir) || portalDir}; entry dist/release-entry.ts`);
